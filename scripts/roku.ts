/**
 * Builds, checks and installs the Roku app (roku/).
 *
 *   pnpm roku:check    check the BrightScript for errors
 *   pnpm roku:build    package it as out/multistream-roku.zip
 *   pnpm roku:deploy   install it on a Roku in developer mode
 *
 * Settings come from .env: ROKU_API_BASE (the Pi's address as the Roku reaches it), and for deploy
 * ROKU_HOST and ROKU_DEV_PASSWORD (the developer-mode password set on the TV).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { z } from "zod";
import { ProgramBuilder, type BsConfig } from "brighterscript";

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const ROKU_DIR = join(PROJECT_ROOT, "roku");
const OUT_DIR = join(PROJECT_ROOT, "out");
export const PACKAGE_PATH = join(OUT_DIR, "multistream-roku.zip");
const CONFIG_PATH = join(OUT_DIR, "roku-config.brs");

export type Command = "check" | "build" | "deploy";

/** "http://192.168.68.59:8080/" -> "http://192.168.68.59:8080". Throws on anything that isn't a plain origin. */
export function normalizeApiBase(raw: string): string {
  const value = raw.trim().replace(/\/+$/, "");
  if (!/^https?:\/\/[A-Za-z0-9.-]+(:\d{1,5})?$/.test(value)) {
    throw new Error(`ROKU_API_BASE must look like http://192.168.68.59:8080 (got "${raw}")`);
  }
  return value;
}

/** The generated BrightScript that tells the Roku app where the Pi is. */
export function configSource(apiBase: string): string {
  return [
    "' Generated by scripts/roku.ts from ROKU_API_BASE. Do not edit.",
    "function AppConfig() as object",
    `    return { apiBase: "${normalizeApiBase(apiBase)}" }`,
    "end function",
    "",
  ].join("\n");
}

/** A setting that must be present and non-blank, with the same message either way. */
const required = (message: string) => z.string({ error: message }).trim().min(1, message);

const buildEnv = z.object({ ROKU_API_BASE: required("ROKU_API_BASE is missing from .env") });
const deployEnv = buildEnv.extend({
  ROKU_HOST: required("ROKU_HOST is missing from .env (the TV's IP address)"),
  ROKU_DEV_PASSWORD: required("ROKU_DEV_PASSWORD is missing from .env (set on the TV in developer mode)"),
});

export interface RokuSettings {
  apiBase: string;
  host?: string;
  password?: string;
}

/** Reads the settings a command needs, with readable errors for missing ones. */
export function readSettings(command: Command, env: Record<string, string | undefined>): RokuSettings {
  // Checking the code doesn't depend on where the Pi is, so it gets a placeholder.
  if (command === "check") return { apiBase: env.ROKU_API_BASE?.trim() || "http://127.0.0.1:8080" };
  const schema = command === "deploy" ? deployEnv : buildEnv;
  const parsed = schema.safeParse(env);
  if (!parsed.success) throw new Error(parsed.error.issues.map((i) => i.message).join("\n"));
  const data = parsed.data as z.infer<typeof deployEnv>;
  return { apiBase: normalizeApiBase(data.ROKU_API_BASE), host: data.ROKU_HOST, password: data.ROKU_DEV_PASSWORD };
}

/** BrighterScript options for a command. */
export function bsOptions(command: Command, settings: RokuSettings, configPath = CONFIG_PATH): BsConfig {
  return {
    rootDir: ROKU_DIR,
    files: [
      "manifest",
      "source/**/*",
      "components/**/*",
      "images/**/*",
      { src: configPath, dest: "source/generated/config.brs" },
    ],
    stagingDir: join(OUT_DIR, "roku-staging"),
    outFile: PACKAGE_PATH,
    createPackage: command !== "check",
    copyToStaging: command !== "check",
    deploy: command === "deploy",
    host: settings.host,
    password: settings.password,
    retainStagingDir: false,
    watch: false,
  };
}

/** Error diagnostics from a check of the Roku code, as "file:line message" strings. */
export async function checkRoku(configPath = CONFIG_PATH): Promise<string[]> {
  mkdirSync(dirname(configPath), { recursive: true });
  writeFileSync(configPath, configSource("http://127.0.0.1:8080"));
  const builder = new ProgramBuilder();
  await builder.run({ ...bsOptions("check", { apiBase: "http://127.0.0.1:8080" }, configPath), logLevel: "error" });
  return builder
    .getDiagnostics()
    .filter((d) => d.severity === 1)
    .map((d) => `${d.file?.srcPath ?? "?"}:${d.range.start.line + 1} ${d.message}`);
}

async function main(): Promise<void> {
  const command = process.argv[2] as Command;
  if (!["check", "build", "deploy"].includes(command)) {
    console.error("Usage: tsx scripts/roku.ts check|build|deploy");
    process.exit(2);
  }
  try {
    process.loadEnvFile(join(PROJECT_ROOT, ".env"));
  } catch {
    // No .env: the settings check below says what's missing.
  }

  const settings = readSettings(command, process.env);
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(CONFIG_PATH, configSource(settings.apiBase));

  const builder = new ProgramBuilder();
  await builder.run(bsOptions(command, settings));
  const errors = builder.getDiagnostics().filter((d) => d.severity === 1);
  if (errors.length > 0) {
    console.error(`\n${errors.length} error(s) in the Roku app; see above.`);
    process.exit(1);
  }
  if (command === "check") console.log("Roku app: no errors.");
  if (command === "build") console.log(`Roku app packaged: ${PACKAGE_PATH}`);
  if (command === "deploy") console.log(`Roku app installed on ${settings.host}.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
